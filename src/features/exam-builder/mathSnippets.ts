export type MathSnippetCategory = 'structure' | 'calculus' | 'geometry' | 'symbols';

export interface MathSnippetItem {
  readonly id: string;
  readonly category: MathSnippetCategory;
  readonly label: string;
  readonly preview: string;
  readonly title: string;
  /** Đoạn mã chèn trước vùng đang bôi đen (hoặc tại vị trí con trỏ) */
  readonly insertBefore: string;
  /** Đoạn mã chèn sau vùng đang bôi đen */
  readonly insertAfter?: string;
  /** Văn bản mẫu đặt bên trong nếu không bôi đen */
  readonly placeholder?: string;
  /** Có cần tự bọc `$ ... $` nếu con trỏ đang nằm ngoài vùng toán học không */
  readonly wrapMathIfOutside?: boolean;
}

